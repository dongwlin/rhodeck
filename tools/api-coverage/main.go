package main

import (
	"flag"
	"fmt"
	"os"
	"sort"
	"text/tabwriter"
)

func main() {
	root := flag.String("root", ".", "repository root containing packages/, apps/, and tools/")
	modeFlag := flag.String("mode", string(ModeDrift), "check mode: drift (source must match the frozen inventory) or final (additionally requires zero pending items)")
	emit := flag.Bool("emit", false, "print the scanned surface as an inventory symbol table instead of checking")
	flag.Parse()

	mode, err := parseMode(*modeFlag)
	if err != nil {
		fmt.Fprintln(os.Stderr, "api-coverage:", err)
		os.Exit(2)
	}

	scan, err := ScanBinding(*root)
	if err != nil {
		fmt.Fprintln(os.Stderr, "api-coverage:", err)
		os.Exit(2)
	}

	if *emit {
		emitSymbols(scan)
		return
	}

	report, err := Check(scan, *root, mode)
	if err != nil {
		fmt.Fprintln(os.Stderr, "api-coverage:", err)
		os.Exit(2)
	}
	printReport(report)
	if !report.Pass {
		os.Exit(1)
	}
}

func emitSymbols(symbols []Symbol) {
	sorted := append([]Symbol(nil), symbols...)
	sort.Slice(sorted, func(i, j int) bool {
		if sorted[i].Kind != sorted[j].Kind {
			return sorted[i].Kind < sorted[j].Kind
		}
		if sorted[i].Owner != sorted[j].Owner {
			return sorted[i].Owner < sorted[j].Owner
		}
		return sorted[i].Name < sorted[j].Name
	})
	fmt.Println("// Code generated by 'go run ./tools/api-coverage --emit'; reconcile by hand.")
	fmt.Println("var frozenSymbols = []Symbol{")
	for _, s := range sorted {
		fmt.Printf("\t{Kind: %q, Owner: %q, Name: %q, Detail: %q},\n", s.Kind, s.Owner, s.Name, s.Detail)
	}
	fmt.Println("}")
}

func printReport(r *Report) {
	fmt.Printf("api-coverage mode=%s scanned=%d frozen=%d done=%d pending=%d na=%d pass=%t\n",
		r.Mode, r.Scanned, r.Frozen, r.Done, r.Pending, r.NA, r.Pass)
	failures := 0
	failures += printSection("added source items (register them in the inventory)", r.Added)
	failures += printSection("removed source items (delete them from the inventory)", r.Removed)
	failures += printSection("changed declarations (update the inventory detail)", r.Changed)
	w := tabwriter.NewWriter(os.Stdout, 0, 4, 2, ' ', 0)
	for _, f := range r.Mapping {
		failures++
		fmt.Fprintf(w, "mapping failure\t%s\t%s\n", f.Item, f.Problem)
	}
	w.Flush()
	if len(r.Gaps) > 0 {
		fmt.Printf("pending gaps (%d), allowed in drift mode, failing in final mode:\n", len(r.Gaps))
		for _, gap := range r.Gaps {
			fmt.Printf("  - %s\n", gap)
		}
	}
	if failures == 0 && r.Pass {
		fmt.Printf("check passed (%d registered gaps allowed in %s mode)\n", len(r.Gaps), r.Mode)
	} else {
		fmt.Printf("check failed (%d failures)\n", failures)
	}
}

func printSection(title string, items []string) int {
	if len(items) == 0 {
		return 0
	}
	fmt.Printf("%s (%d):\n", title, len(items))
	for _, item := range items {
		fmt.Printf("  - %s\n", item)
	}
	return len(items)
}
